"""Generate the six chess piece STL meshes (binary, metres, origin = centre of base bottom, z up).

Run:  simulation/.venv-sim/bin/python simulation/assets/chess/make_pieces.py
Dimensions (height, base diameter, top diameter) come from simulation/config/pieces.yaml; the profile
shapes were designed from the phone photos (turned wooden pieces). Lathe pieces are revolved
(r, z) profiles; the rook adds merlons, the king a cross, the knight an extruded horse-head
silhouette (muzzle toward +x) on a revolved base. numpy only.
"""
import math
import struct
import sys
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
CFG = HERE.parents[1] / "config" / "pieces.yaml"


def arc(cx, cz, r, a0, a1, n=10):
    a = np.radians(np.linspace(a0, a1, n))
    return [(cx + r * math.cos(t), cz + r * math.sin(t)) for t in a]


def revolve(profile, seg):
    """profile: list of (r, z) from bottom (r=0) to top (r=0). Returns (V, F) outward-facing."""
    prof = np.asarray(profile, float)
    ang = np.linspace(0, 2 * np.pi, seg, endpoint=False)
    V = []
    for r, z in prof:
        for a in ang:
            V.append((r * math.cos(a), r * math.sin(a), z))
    V = np.array(V)
    F = []
    n = len(prof)
    for i in range(n - 1):
        for j in range(seg):
            j2 = (j + 1) % seg
            a, b = i * seg + j, i * seg + j2
            c, d = (i + 1) * seg + j2, (i + 1) * seg + j
            F += [(a, b, c), (a, c, d)]
    return V, np.array(F)


def vol(V, F):
    a, b, c = V[F[:, 0]], V[F[:, 1]], V[F[:, 2]]
    return np.einsum("ij,ij->i", a, np.cross(b, c)).sum() / 6


def clean(V, F):
    a, b, c = V[F[:, 0]], V[F[:, 1]], V[F[:, 2]]
    area = np.linalg.norm(np.cross(b - a, c - a), axis=1)
    F = F[area > 1e-12]
    if vol(V, F) < 0:
        F = F[:, ::-1]
    return V, F


def merge(parts):
    Vs, Fs, off = [], [], 0
    for V, F in parts:
        V, F = clean(V, F)
        Vs.append(V)
        Fs.append(F + off)
        off += len(V)
    return np.vstack(Vs), np.vstack(Fs)


def box(x0, x1, y0, y1, z0, z1):
    V = np.array([(x, y, z) for z in (z0, z1) for y in (y0, y1) for x in (x0, x1)], float)
    q = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    F = []
    for a, b, c, d in q:
        F += [(a, b, c), (a, c, d)]
    return V, np.array(F)


def sector_prism(r0, r1, a0, a1, z0, z1, n=6):
    """Ring sector solid (a merlon)."""
    ang = np.linspace(a0, a1, n)
    ring = [(r1 * math.cos(a), r1 * math.sin(a)) for a in ang] + \
           [(r0 * math.cos(a), r0 * math.sin(a)) for a in ang[::-1]]
    return extrude_polygon_xy(ring, z0, z1)


def earclip(P):
    P = [tuple(p) for p in P]
    idx = list(range(len(P)))
    area = sum(P[i][0] * P[(i + 1) % len(P)][1] - P[(i + 1) % len(P)][0] * P[i][1] for i in range(len(P)))
    if area < 0:
        idx.reverse()
    tris = []

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = P[i0], P[i1], P[i2]
            if cross(a, b, c) <= 1e-12:
                continue
            ok = True
            for m in idx:
                if m in (i0, i1, i2):
                    continue
                p = P[m]
                if cross(a, b, p) >= 0 and cross(b, c, p) >= 0 and cross(c, a, p) >= 0:
                    ok = False
                    break
            if ok:
                tris.append((i0, i1, i2))
                idx.pop(k)
                break
    tris.append(tuple(idx))
    return tris


def extrude_polygon_xy(poly, z0, z1):
    n = len(poly)
    V = np.array([(x, y, z0) for x, y in poly] + [(x, y, z1) for x, y in poly], float)
    F = []
    for a, b, c in earclip(poly):
        F.append((a, c, b))              # bottom (flipped; clean() fixes global sign)
        F.append((a + n, b + n, c + n))
    for i in range(n):
        j = (i + 1) % n
        F += [(i, j, j + n), (i, j + n, i + n)]
    return V, np.array(F)


def write_stl(path, V, F):
    V, F = clean(V, F)
    tri = V[F]
    nrm = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    nrm /= np.linalg.norm(nrm, axis=1, keepdims=True)
    with open(path, "wb") as f:
        f.write(b"chess piece generated by make_pieces.py".ljust(80, b" "))
        f.write(struct.pack("<I", len(F)))
        rec = np.zeros(len(F), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
        rec["n"], rec["v"] = nrm, tri
        f.write(rec.tobytes())


def base(R, ring=None):
    """Common turned base: disc (full radius R to z=1.6), step, ring, to z=3.0 (mm)."""
    ring = ring if ring is not None else R - 1.3
    return [(0, 0), (R - 0.5, 0), (R, 0.5), (R, 1.5), (R - 0.5, 1.9), (ring + 0.3, 2.0), (ring, 2.2),
            (ring, 2.8), (ring - 0.8, 3.1)]


def profile_pawn(c):
    R, rh = c["measured"]["base_diameter_mm"] / 2, c["measured"]["top_diameter_mm"] / 2
    zc = c["measured"]["height_mm"] - rh
    p = base(R) + [(2.7, 4.2), (2.35, 6.0), (2.3, 8.2), (3.4, 8.7), (4.0, 8.9), (4.0, 9.6), (2.9, 9.9),
                   (2.3, 10.4), (2.3, 11.2)]
    p += arc(0, zc, rh, -40, 90, 14)
    p[-1] = (0, zc + rh)
    return p


def profile_rook(c):
    R, rt = c["measured"]["base_diameter_mm"] / 2, c["measured"]["top_diameter_mm"] / 2
    zt = c["measured"]["height_mm"]
    zf = 18.4  # floor between merlons
    p = base(R) + [(3.9, 4.6), (3.7, 6.5), (3.7, 13.0), (4.3, 13.4), (4.3, 14.2), (3.8, 14.6), (3.8, 15.2),
                   (rt, 16.4), (rt, zf), (0, zf)]
    return p, rt, zf, zt


def profile_bishop(c):
    R, rm = c["measured"]["base_diameter_mm"] / 2, c["measured"]["top_diameter_mm"] / 2
    H = c["measured"]["height_mm"]
    rb = 1.6
    zb = H - rb
    zc, bz = 19.2, 4.3
    p = base(R) + [(3.0, 4.6), (2.9, 7.0), (2.9, 12.6), (4.2, 13.0), (4.2, 14.0), (2.7, 14.4), (2.7, 14.9),
                   (3.6, 15.1)]
    p += [(rm * math.cos(math.radians(a)), zc + bz * math.sin(math.radians(a))) for a in range(-55, 71, 9)]
    p += [(1.0, 23.5), (1.0, 24.1)]
    p += arc(0, zb, rb, -48, 90, 10)
    p[-1] = (0, H)
    return p


def profile_queen(c):
    R, rc = c["measured"]["base_diameter_mm"] / 2, c["measured"]["top_diameter_mm"] / 2
    H = c["measured"]["height_mm"]
    rb = 1.5
    p = base(R) + [(3.0, 4.6), (2.9, 7.0), (2.9, 12.6), (4.2, 13.0), (4.2, 14.0), (2.7, 14.4), (2.7, 15.2),
                   (3.4, 16.5), (4.2, 18.5), (rc - 0.4, 20.5), (rc, 21.6), (rc, 23.0), (rc - 0.5, 23.6),
                   (3.2, 23.8), (3.2, 24.1), (2.0, 24.4)]
    p += arc(0, H - rb, rb, -40, 90, 10)
    p[-1] = (0, H)
    return p


def profile_king(c):
    R, rc = c["measured"]["base_diameter_mm"] / 2, c["measured"]["top_diameter_mm"] / 2
    p = base(R) + [(3.1, 4.8), (3.0, 7.0), (3.0, 14.6), (4.5, 15.0), (4.5, 16.0), (2.8, 16.5), (2.8, 17.4),
                   (3.8, 19.0), (4.6, 21.5), (rc, 24.0), (rc, 26.0), (rc - 0.6, 27.0), (2.2, 27.2), (2.2, 28.7),
                   (0, 28.7)]
    return p


def horse_polygon(H):
    z_tip = H
    return [(-3.8, 8.0), (-4.0, 13.0), (-3.6, 18.0), (-3.0, z_tip - 3.0), (-2.4, z_tip), (-1.4, z_tip - 1.8),
            (-0.7, z_tip - 0.2), (0.4, z_tip - 1.8), (2.8, z_tip - 4.0), (5.6, z_tip - 7.6), (6.0, z_tip - 8.9),
            (5.6, z_tip - 10.3), (4.0, z_tip - 10.5), (3.0, z_tip - 9.6), (2.6, z_tip - 12.4), (3.6, 9.6),
            (3.6, 8.0)]


def build_knight(c, seg):
    R = c["measured"]["base_diameter_mm"] / 2
    H = c["measured"]["height_mm"]
    p = base(R) + [(3.9, 4.4), (3.9, 5.8), (4.9, 6.3), (4.9, 7.7), (4.6, 8.2), (0, 8.2)]
    parts = [revolve(p, seg)]
    poly = horse_polygon(H)
    # loft: half width in y tapers with height (thick neck -> narrow head)
    def hw(z):
        return float(np.interp(z, [8.0, 14.0, 20.0, H], [3.1, 2.7, 2.2, 1.3]))
    n = len(poly)
    # slightly refine: subdivide long edges so the taper is smooth
    pts = []
    for i in range(n):
        a, b = poly[i], poly[(i + 1) % n]
        k = max(1, int(math.dist(a, b) // 2.5))
        for t in range(k):
            pts.append((a[0] + (b[0] - a[0]) * t / k, a[1] + (b[1] - a[1]) * t / k))
    if sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts))) < 0:
        pts.reverse()  # make CCW in (x, z) so side/cap windings agree
    m = len(pts)
    V = np.array([(x, -hw(z), z) for x, z in pts] + [(x, hw(z), z) for x, z in pts], float)
    F = []
    for a, b, d in earclip(pts):
        F.append((a, b, d))
        F.append((a + m, d + m, b + m))
    for i in range(m):
        j = (i + 1) % m
        F += [(i, i + m, j + m), (i, j + m, j)]
    parts.append((V, np.array(F)))
    return parts


def build(name, c, seg):
    if name == "pawn":
        parts = [revolve(profile_pawn(c), seg)]
    elif name == "rook":
        p, rt, zf, zt = profile_rook(c)
        parts = [revolve(p, seg)]
        for k in range(6):
            a0 = math.radians(60 * k + 6)
            a1 = math.radians(60 * k + 54)
            parts.append(sector_prism(3.3, rt, a0, a1, zf - 0.1, zt))
    elif name == "bishop":
        parts = [revolve(profile_bishop(c), seg)]
    elif name == "queen":
        parts = [revolve(profile_queen(c), seg)]
    elif name == "king":
        H = c["measured"]["height_mm"]
        parts = [revolve(profile_king(c), seg), box(-0.8, 0.8, -0.8, 0.8, 28.5, H),
                 box(-2.2, 2.2, -0.8, 0.8, 31.0, 32.6)]
    elif name == "knight":
        parts = build_knight(c, seg)
    V, F = merge(parts)
    return V * 1e-3, F  # metres


def main(outdir=None):
    cfg = yaml.safe_load(open(CFG))
    outdir = Path(outdir) if outdir else HERE
    for name, c in cfg["pieces"].items():
        V, F = build(name, c, cfg["mesh_segments"])
        write_stl(outdir / f"{name}.stl", V, F)
        ext = V.max(0) - V.min(0)
        print(f"{name:7s} tris={len(F):5d} height={V[:,2].max()*1e3:.2f}mm zmin={V[:,2].min()*1e3:.3f} "
              f"extent_xy={ext[0]*1e3:.2f}x{ext[1]*1e3:.2f}mm vol={abs(vol(V,F))*1e9:.0f}mm3")


if __name__ == "__main__":
    main(*sys.argv[1:])
